export function generatePortalJobs(filters = {}) {
  const { role, skills = [], location, jobType, experience, company } = filters;
  const studentSkills = (Array.isArray(skills) ? skills : (skills ? skills.split(',') : []))
    .map(s => s.trim().toLowerCase())
    .filter(Boolean);

  let jobs = [];
  let idCounter = 1;

  for (const portal of CAREER_PORTALS) {
    if (company && company.toLowerCase() !== 'any' && !portal.name.toLowerCase().includes(company.toLowerCase())) {
      continue;
    }

    for (const portalRole of portal.roles) {
      if (role && role.toLowerCase() !== 'any') {
        const roleMatch = portalRole.title.toLowerCase().includes(role.toLowerCase()) ||
                          role.toLowerCase().includes(portalRole.title.toLowerCase().split(' ')[0]);
        if (!roleMatch) continue;
      }

      if (jobType && jobType.toLowerCase() !== 'any' && portalRole.jobType.toLowerCase() !== jobType.toLowerCase()) {
        continue;
      }

      if (experience && experience.toLowerCase() !== 'any' && portalRole.experience.toLowerCase() !== experience.toLowerCase()) {
        continue;
      }

      const roleSkillsLower = portalRole.skills.map(s => s.toLowerCase());
      const matched = studentSkills.filter(s =>
        roleSkillsLower.some(rs => rs.includes(s) || s.includes(rs))
      );
      const matchPercent = roleSkillsLower.length > 0 && studentSkills.length > 0
        ? Math.round((matched.length / roleSkillsLower.length) * 100)
        : (studentSkills.length === 0 ? 0 : 0);

      const searchTerm = encodeURIComponent(portalRole.title);
      const applicationUrl = portal.searchUrl
        ? `${portal.searchUrl}${searchTerm}`
        : portal.careerUrl;

      jobs.push({
        id: `portal-${portal.id}-${idCounter++}`,
        companyName: portal.name,
        companyLogo: portal.logo,
        title: portalRole.title,
        location: location && location !== 'Any Location' ? location : 'India',
        jobType: portalRole.jobType,
        experience: portalRole.experience,
        salary: null,
        description: `Explore ${portalRole.title} opportunities at ${portal.name}. Visit the official career portal to view current openings and apply directly.`,
        skills: portalRole.skills,
        postedDate: null,
        source: 'career_portal',
        sourceName: `${portal.name} Careers`,
        applicationUrl,
        matchPercent,
        matchedSkills: matched.map(s => {
          const original = portalRole.skills.find(rs => rs.toLowerCase().includes(s) || s.includes(rs.toLowerCase()));
          return original || s;
        }),
        missingSkills: portalRole.skills.filter(rs =>
          !matched.some(m => rs.toLowerCase().includes(m) || m.includes(rs.toLowerCase()))
        ),
        category: portal.category,
      });
    }
  }

  jobs.sort((a, b) => b.matchPercent - a.matchPercent);
  return jobs;
}
